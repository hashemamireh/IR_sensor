void Framebuffer::clear() { memset(buf_, 0, sizeof(buf_)); }

void Framebuffer::set_pixel(int x, int y, bool on) {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return;
    uint8_t& b = buf_[(y / 8) * WIDTH + x];
    uint8_t mask = static_cast<uint8_t>(1u << (y % 8));
    b = on ? (b | mask) : (b & ~mask);
}

bool Framebuffer::pixel(int x, int y) const {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return false;
    return buf_[(y / 8) * WIDTH + x] & (1u << (y % 8));
}

void Framebuffer::fill_rect(int x, int y, int w, int h, bool on) {
    for (int yy = y; yy < y + h; yy++) {
        for (int xx = x; xx < x + w; xx++) set_pixel(xx, yy, on);
    }
}

void Framebuffer::rect(int x, int y, int w, int h, bool on) {
    fill_rect(x, y, w, 1, on);
    fill_rect(x, y + h - 1, w, 1, on);
    fill_rect(x, y, 1, h, on);
    fill_rect(x + w - 1, y, 1, h, on);
}

int Framebuffer::text(int x, int y, const char* s, bool on) {
    int start = x;
    for (; *s; s++, x += CHAR_W) {
        unsigned char c = static_cast<unsigned char>(*s);
        if (c < 0x20 || c > 0x7E) c = '?';
        const uint8_t* glyph = FONT[c - 0x20];
        for (int col = 0; col < 5; col++) {
            for (int row = 0; row < CHAR_H; row++) {
                if (glyph[col] & (1u << row)) set_pixel(x + col, y + row, on);
            }
        }
    }
    return x - start;
}

int Framebuffer::text_width(const char* s) {
    return static_cast<int>(strlen(s)) * CHAR_W;
}

std::string Framebuffer::to_ascii() const {
    std::string out;
    out.reserve((WIDTH + 1) * HEIGHT);
    for (int y = 0; y < HEIGHT; y++) {
        for (int x = 0; x < WIDTH; x++) out += pixel(x, y) ? '#' : '.';
        out += '\n';
    }
    return out;
}

